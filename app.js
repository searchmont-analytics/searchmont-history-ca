/* Searchmont History: menu, photo viewer, search and kiosk mode.
   Pages themselves are plain HTML generated by build.py. */
(function () {
  const root = document.body.dataset.root || './';

  // Links from the earlier one-page version (#/townsite/hotel) -> real pages
  if (/^#\/./.test(location.hash)) {
    location.replace(root + location.hash.slice(2).replace(/\/?$/, '/'));
    return;
  }

  /* ---------- Menu (phones) ---------- */
  const nav = document.getElementById('topnav');
  const menuBtn = document.querySelector('.menu-btn');
  menuBtn.addEventListener('click', () => {
    const open = nav.classList.toggle('open');
    menuBtn.setAttribute('aria-expanded', open);
  });

  /* ---------- Photo viewer ---------- */
  const lb = document.getElementById('lightbox');
  const lbImg = document.getElementById('lb-img');
  const lbCap = document.getElementById('lb-caption');
  const lbCount = document.getElementById('lb-count');
  const lbFull = document.getElementById('lb-full');
  let list = [], at = 0, lastFocus = null;

  /* zoom & pan: wheel / pinch / double-click / +− buttons, drag to move */
  const stage = document.getElementById('lb-stage');
  const zoomLabel = document.getElementById('lb-zoom-level');
  let z = 1, tx = 0, ty = 0;
  const MAXZ = 8;
  function apply(animate) {
    lbImg.style.transition = animate ? 'transform .2s ease' : 'none';
    lbImg.style.transform = `translate(${tx}px, ${ty}px) scale(${z})`;
    lb.classList.toggle('zoomed', z > 1.01);
    zoomLabel.textContent = Math.round(z * 100) + '%';
  }
  function clamp() {
    // keep the photo from being dragged off screen
    const r = stage.getBoundingClientRect();
    const w = lbImg.offsetWidth * z, h = lbImg.offsetHeight * z;
    const mx = Math.max(0, (w - r.width) / 2), my = Math.max(0, (h - r.height) / 2);
    tx = Math.min(mx, Math.max(-mx, tx)); ty = Math.min(my, Math.max(-my, ty));
  }
  function zoomAt(nz, cx, cy, animate) {
    // cx, cy: point (relative to stage centre) that should stay under the pointer
    nz = Math.min(MAXZ, Math.max(1, nz));
    tx = cx - (cx - tx) * (nz / z); ty = cy - (cy - ty) * (nz / z); z = nz;
    if (z === 1) { tx = 0; ty = 0; }
    clamp(); apply(animate);
  }
  function reset() { z = 1; tx = 0; ty = 0; apply(false); }
  const centre = (x, y) => { const r = stage.getBoundingClientRect(); return [x - r.left - r.width / 2, y - r.top - r.height / 2]; };

  stage.addEventListener('wheel', (e) => {
    e.preventDefault();
    const [cx, cy] = centre(e.clientX, e.clientY);
    zoomAt(z * Math.exp(-e.deltaY * 0.0022), cx, cy, false);
  }, { passive: false });
  lbImg.addEventListener('dblclick', (e) => {
    const [cx, cy] = centre(e.clientX, e.clientY);
    zoomAt(z > 1.01 ? 1 : 2.5, cx, cy, true);
  });
  document.getElementById('lb-zoom-in').onclick = () => zoomAt(z * 1.5, 0, 0, true);
  document.getElementById('lb-zoom-out').onclick = () => zoomAt(z / 1.5, 0, 0, true);
  document.getElementById('lb-zoom-reset').onclick = () => { reset(); apply(true); };

  // pointer drag + pinch (works for mouse, pen and touch)
  const pts = new Map();
  let pinch = null, drag = null, moved = false, lastTap = 0;
  lbImg.addEventListener('pointerdown', (e) => {
    lbImg.setPointerCapture(e.pointerId);
    pts.set(e.pointerId, { x: e.clientX, y: e.clientY });
    moved = false;
    if (pts.size === 2) {
      const [a, b] = [...pts.values()];
      pinch = { d: Math.hypot(a.x - b.x, a.y - b.y), z, c: centre((a.x + b.x) / 2, (a.y + b.y) / 2) };
      drag = null;
    } else if (pts.size === 1) {
      drag = { x: e.clientX, y: e.clientY, tx, ty };
    }
  });
  lbImg.addEventListener('pointermove', (e) => {
    if (!pts.has(e.pointerId)) return;
    pts.set(e.pointerId, { x: e.clientX, y: e.clientY });
    if (pinch && pts.size === 2) {
      const [a, b] = [...pts.values()];
      const d = Math.hypot(a.x - b.x, a.y - b.y);
      zoomAt(pinch.z * d / pinch.d, pinch.c[0], pinch.c[1], false);
      moved = true;
    } else if (drag && z > 1.01) {
      tx = drag.tx + e.clientX - drag.x; ty = drag.ty + e.clientY - drag.y;
      if (Math.abs(e.clientX - drag.x) + Math.abs(e.clientY - drag.y) > 4) moved = true;
      clamp(); apply(false);
    }
  });
  const up = (e) => {
    if (!pts.has(e.pointerId)) return;
    pts.delete(e.pointerId);
    if (pts.size < 2) pinch = null;
    if (pts.size === 0) {
      // double-tap to zoom on touch screens
      if (e.pointerType === 'touch' && !moved) {
        const now = Date.now();
        if (now - lastTap < 300) { const [cx, cy] = centre(e.clientX, e.clientY); zoomAt(z > 1.01 ? 1 : 2.5, cx, cy, true); lastTap = 0; }
        else lastTap = now;
      }
      drag = null;
    }
  };
  lbImg.addEventListener('pointerup', up);
  lbImg.addEventListener('pointercancel', up);
  lbImg.addEventListener('dragstart', (e) => e.preventDefault());

  function show(i) {
    at = (i + list.length) % list.length;
    const b = list[at];
    reset();
    lbImg.src = b.dataset.full;
    lbImg.alt = b.querySelector('img').alt;
    lbCap.textContent = b.dataset.caption || '';
    lbCount.textContent = `Photo ${at + 1} of ${list.length}`;
    lbFull.href = b.dataset.full;
    [at + 1, at - 1].forEach((j) => { const n = list[(j + list.length) % list.length]; if (n) new Image().src = n.dataset.full; });
  }
  function open(btn) {
    list = [...document.querySelectorAll('main .photo')];
    lastFocus = btn; lb.hidden = false; document.body.style.overflow = 'hidden';
    show(list.indexOf(btn)); document.getElementById('lb-close').focus();
  }
  function close() { lb.hidden = true; document.body.style.overflow = ''; lbImg.removeAttribute('src'); lastFocus && lastFocus.focus(); }

  document.querySelector('main').addEventListener('click', (e) => { const b = e.target.closest('.photo'); if (b) open(b); });
  document.getElementById('lb-prev').onclick = () => show(at - 1);
  document.getElementById('lb-next').onclick = () => show(at + 1);
  document.getElementById('lb-close').onclick = close;
  document.getElementById('lb-stage').addEventListener('click', (e) => { if (e.target.id === 'lb-stage') close(); });
  document.addEventListener('keydown', (e) => {
    if (lb.hidden) return;
    if (e.key === 'Escape') { if (z > 1.01) { reset(); apply(true); } else close(); }
    else if (e.key === 'ArrowLeft') show(at - 1);
    else if (e.key === 'ArrowRight') show(at + 1);
    else if (e.key === '+' || e.key === '=') zoomAt(z * 1.5, 0, 0, true);
    else if (e.key === '-') zoomAt(z / 1.5, 0, 0, true);
    else if (e.key === '0') { reset(); apply(true); }
  });
  // swipe left/right to change photo (only when not zoomed in)
  let x0 = null, multi = false;
  lb.addEventListener('touchstart', (e) => { multi = e.touches.length > 1; x0 = z > 1.01 ? null : e.touches[0].clientX; }, { passive: true });
  lb.addEventListener('touchend', (e) => {
    if (x0 === null || multi || z > 1.01) { x0 = null; return; }
    const dx = e.changedTouches[0].clientX - x0; x0 = null;
    if (Math.abs(dx) > 60) show(at + (dx < 0 ? 1 : -1));
  });

  /* ---------- Search page ---------- */
  const results = document.getElementById('results');
  if (results) {
    const params = new URLSearchParams(location.search);
    const q = (params.get('q') || '').trim();
    const status = document.getElementById('search-status');
    document.getElementById('q2').value = q;
    document.getElementById('q').value = q;
    const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
    const norm = (s) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
    if (q) {
      status.textContent = 'Searching…';
      fetch(root + 'search-index.json').then((r) => r.json()).then((idx) => {
        const words = norm(q).split(/\s+/).filter(Boolean);
        const hits = idx.map((d) => {
          const cap = norm(d.c), txt = norm(d.x), title = norm(d.p + ' ' + d.t);
          if (!words.every((w) => cap.includes(w) || txt.includes(w) || title.includes(w))) return null;
          const score = words.reduce((n, w) => n + (title.includes(w) ? 3 : 0) + (cap.includes(w) ? 2 : 0) + (txt.includes(w) ? 1 : 0), 0);
          return { d, score };
        }).filter(Boolean).sort((a, b) => b.score - a.score);
        status.textContent = hits.length ? `${hits.length} result${hits.length === 1 ? '' : 's'} for “${q}”` : `No results for “${q}”. Try fewer or different words.`;
        const mark = (s) => { let h = esc(s); words.forEach((w) => { h = h.replace(new RegExp('(' + w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')', 'gi'), '<mark>$1</mark>'); }); return h; };
        const snippet = (d) => {
          const src = d.c + (d.x ? ' … ' + d.x : ''), flat = src.replace(/\s+/g, ' ');
          const i = norm(flat).indexOf(words[0]);
          const s = Math.max(0, i - 80);
          return (s ? '…' : '') + flat.slice(s, s + 240) + (flat.length > s + 240 ? '…' : '');
        };
        results.innerHTML = hits.slice(0, 100).map(({ d }) => `
          <a class="result" href="${root}${d.u}">
            ${d.i ? `<img loading="lazy" src="${root}${d.i}" alt="">` : '<span class="noimg"></span>'}
            <span><span class="where">${esc(d.t)} › ${esc(d.p)}</span>
            <span class="what">${mark(snippet(d))}</span></span></a>`).join('');
      }).catch(() => { status.textContent = 'Search could not load. Please try again.'; });
    }
  }

  /* ---------- Community-centre touch screen ----------
     Open any page with ?kiosk to return to the home page after 15 minutes idle. */
  try {
    if (/[?&]kiosk\b/.test(location.search)) sessionStorage.setItem('kiosk', '1');
    if (sessionStorage.getItem('kiosk')) {
      let timer;
      const reset = () => { clearTimeout(timer); timer = setTimeout(() => { location.href = root; }, 15 * 60 * 1000); };
      ['pointerdown', 'keydown', 'touchstart', 'scroll'].forEach((ev) => window.addEventListener(ev, reset, { passive: true }));
      reset();
    }
  } catch (e) { /* storage blocked: kiosk timer simply off */ }
})();
